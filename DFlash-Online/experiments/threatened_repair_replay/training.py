"""Opt-in disposable replay windows around the unchanged native K+ update."""
from contextlib import nullcontext
from copy import deepcopy
import math
from pathlib import Path
import time
import traceback

from experiments.recent_repair_retention.training import RecentRetentionTrainer
from online_feedback.storage import write_json
from .analysis import WINDOWS
from .state import named_gradients, tensor_change


class ThreatReplayTrainer(RecentRetentionTrainer):
    """Only native rows advance the event; the controller restores disposable states.

    ``on_window`` receives the naturally generated current pair. It must return
    the native ``run_pair`` bundle after restoring its complete endpoint. The
    surrounding pass permutation is never regenerated by a branch.
    """
    def __init__(self, *args, on_window=None, ledger=None, **kwargs):
        self.on_window, self.ledger = on_window, ledger
        super().__init__(*args, arm="NATIVE", **kwargs)

    def _train_passes(self, features, passes):
        import torch
        rows = []
        for pass_index in range(passes):
            order = torch.randperm(len(features)).tolist()
            for offset in range(0, len(order), 2):
                ordinal = len(rows)
                pair = [features[index] for index in order[offset:offset + 2]]
                window = ordinal // 2 + 1
                if self.on_window is not None and window in WINDOWS:
                    result = self.on_window(self, window, pair, pass_index, ordinal)
                else:
                    result = self.run_pair(pair, pass_index, ordinal, label="N", category="native")
                if self.global_step != 768 + window or self.presentations != 1536 + ordinal + 2:
                    raise ValueError("Disposable branching changed the continuing native counters")
                rows.extend(result["rows"])
        self.presentation_ordinal = None
        if len(rows) != 256 or len(self.response_records) != 256 or len(self.window_records) != 128:
            raise ValueError("Native event must retain exactly 256 presentations and 128 windows")
        return rows

    def run_pair(self, pair, pass_index, ordinal, *, label="N", category="native",
                 replay=None, capture_gradients=False, reference_gradients=None):
        """Two native microbatches, optional replay injection, one clip and Adam step.

        The replay callable runs after TrainerCore has averaged the native
        gradients and before DirectBF16AdamW performs its sole global clip.
        It returns a compact receipt; its auxiliary backward is not train_step.
        """
        import torch
        from specforge.training.strategies.base import StepContext
        from experiments.ok_continuation.resume import differences

        if len(pair) != 2 or self.core.accumulation_remainder:
            raise ValueError("Require one complete two-response native window")
        window = ordinal // 2 + 1
        original_step = self._native_step
        original_event = self._active_event
        if category != "native":
            self._active_event = f"{category}_w{window:03d}_{label}"
            (self.events_root / self._active_event).mkdir(exist_ok=False)
        output = self.events_root / self._active_event
        receipt = dict(status="running", window=window, state=label, category=category,
                       start_step=self.global_step, start_presentations=self.presentations,
                       replay=None, optimizer_applications=0)
        captures, rows = {}, []
        scope = self.ledger.scope(category=category, window=window, state=label) if self.ledger is not None else nullcontext()

        def before_clip():
            began = time.perf_counter()
            native_gradient = named_gradients(self) if capture_gradients or replay is not None or reference_gradients is not None else None
            if reference_gradients is not None:
                mismatch = differences(native_gradient, reference_gradients, "native_preclip")
                receipt["native_gradient_parity"] = dict(status="passed" if not mismatch else "failed", mismatches=mismatch[:32])
                write_json(output / "PAIR_UPDATE.json", receipt)
                if mismatch:
                    raise ValueError("Replay branch recomputed different native gradients")
            if replay is not None:
                receipt["replay"] = replay(self)
            if native_gradient is not None:
                combined = named_gradients(self) if replay is not None else native_gradient
                receipt["gradient_change"] = tensor_change(native_gradient, combined)
                if capture_gradients:
                    captures.update(native=native_gradient, combined=combined)
            receipt["gradient_observation_s"] = time.perf_counter() - began
            # original_step is the existing finite-gradient wrapper followed by
            # the native clip/Adam/zero_grad operation. Never call the inner Adam
            # directly here, which would bypass the qualified clipping order.
            result = original_step()
            receipt["optimizer_applications"] += 1
            receipt["combined_native_clip_norm"] = float(result.detach())
            # Mirror clip_grad_norm_'s scalar arithmetic, including BF16
            # rounding, rather than reporting an ideal FP64 coefficient.
            factor = torch.clamp(self.backend.optimizer.max_grad_norm / (result.detach() + 1e-6), max=1.)
            receipt["clip_factor"] = float(factor)
            receipt["clip_factor_dtype"] = str(factor.dtype)
            return result

        self._native_step = before_clip
        started = time.perf_counter()
        try:
            with scope:
                for local, feature in enumerate(pair):
                    self.presentation_ordinal = ordinal + local
                    self._presentation_schedule.begin_presentation(pass_index, feature["record_id"])
                    raw = torch.load(feature["path"], map_location="cpu", weights_only=True)
                    self._anchor_observations.clear()
                    began = time.perf_counter()
                    result = self.core.train_step(self._batch(raw), StepContext(
                        global_step=self.global_step, total_steps=self.horizon, collect_detailed_metrics=True))
                    self._presentation_schedule.finish_presentation()
                    metrics = result.materialize_metrics()
                    elapsed = time.perf_counter() - began
                    self.presentations += 1
                    self.global_step += int(result.optimizer_stepped)
                    if not all(math.isfinite(float(value)) for value in metrics.values()):
                        raise ValueError("Nonfinite native or replay metric")
                    rows.append(dict(record_id=feature["record_id"], **{"pass": pass_index},
                        optimizer_step_after=self.global_step, optimizer_stepped=result.optimizer_stepped,
                        learning_rate=self.backend.optimizer.get_learning_rate() if result.optimizer_stepped else None,
                        metrics=metrics, training_s=elapsed, sampled_anchors=deepcopy(self._anchor_observations),
                        metrics_scope="accumulation_window" if result.optimizer_stepped else "presentation",
                        response_observation=deepcopy(self.response_records[-1]),
                        prompt_tokens=feature["prompt_length"], response_tokens=feature["response_tokens"],
                        feature_path=feature["path"]))
            if receipt["optimizer_applications"] != 1 or [row["optimizer_stepped"] for row in rows] != [False, True]:
                raise ValueError("Replay must not add an optimizer or accumulation application")
            receipt.update(status="completed", end_step=self.global_step, end_presentations=self.presentations,
                           mean_native_response_loss=sum(row["response_observation"]["loss"] for row in rows) / 2)
            return dict(rows=rows, update=receipt, preclip_gradients=captures)
        except BaseException as error:
            receipt.update(status="failed", error=repr(error), traceback=traceback.format_exc(),
                           completed_presentations=len(rows), global_step=self.global_step)
            # The compact failure is durable before it is raised. The controller
            # retains the already captured P/N witness and physical work ledger.
            write_json(output / "PAIR_FAILED.json", receipt)
            raise
        finally:
            self._native_step = original_step
            self._active_event = original_event
            receipt["wall_s"] = time.perf_counter() - started
            write_json(output / f"PAIR_{window:03d}_{label}.json", receipt)


def make_trainer(plan, output, *, on_window=None, ledger=None):
    """Accept the authenticated PR44 native input plan; no artifact guessing."""
    from experiments.recent_repair_retention.reference import read
    return ThreatReplayTrainer(plan["configs"]["NATIVE"], output,
        binding=plan["binding"], origin_state=plan["origin_state"], origin_export=plan["origin_export"],
        original_config_text=Path(plan["origin_config"]).read_text(), schedule=read(plan["schedule"]),
        on_window=on_window, ledger=ledger)
